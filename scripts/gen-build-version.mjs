#!/usr/bin/env node
/**
 * Generate apps/host/src/build-version.ts from the installer-stamped APP version (SPEC §1;
 * AC25/AC26; QA_REPORT.md "Amendments bounced to Backend", GATE Q pass 1g).
 *
 * The version that matters here is the *app* version — the one the NSIS installer stamps and the
 * one a non-developer reads in Settings or a diagnostics file — never `apps/host/package.json`'s
 * own workspace version, which drifts independently of a release (that mismatch is the exact trap
 * named in the bounce: apps/host/package.json says 0.3.0 while the shipped app is 0.3.2).
 *
 * Source of truth: apps/shell/src-tauri/tauri.conf.json's "version" field — the same field Tauri
 * itself stamps into the NSIS installer and the same value the packaged shell's own
 * `getVersion()` returns at runtime. Reading it here at generation time (never at host runtime)
 * makes the host's `/api/health` version and the shell's own version agree by construction
 * instead of by luck, for both the packaged host and a from-source dev host.
 *
 * Generated, not checked in (mirrors allowed-origins.ts / scripts/gen-allowed-origins.mjs): a
 * skipped run must FAIL the build with a missing module rather than silently ship a stale or
 * empty version.
 *
 * Usage: node scripts/gen-build-version.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const confPath = path.join(root, "apps", "shell", "src-tauri", "tauri.conf.json");
const outPath = path.join(root, "apps", "host", "src", "build-version.ts");

if (!fs.existsSync(confPath)) {
  console.error(`[gen-build-version] missing ${confPath}`);
  process.exit(1);
}

let version;
try {
  const conf = JSON.parse(fs.readFileSync(confPath, "utf8"));
  version = conf.version;
} catch (e) {
  console.error(`[gen-build-version] failed to parse ${confPath}: ${String(e)}`);
  process.exit(1);
}

if (typeof version !== "string" || !/^\d+\.\d+\.\d+/.test(version)) {
  console.error(
    `[gen-build-version] tauri.conf.json "version" is missing or not a semver-shaped string: ${JSON.stringify(version)}`,
  );
  process.exit(1);
}

const banner =
  `// GENERATED by scripts/gen-build-version.mjs — do not edit, do not commit.\n` +
  `// Source: apps/shell/src-tauri/tauri.conf.json "version" — the installer-stamped app version\n` +
  `// (SPEC §1, AC25/AC26). Gitignored on purpose: a skipped run must FAIL the build with a\n` +
  `// missing module rather than silently ship a stale version.\n`;

fs.writeFileSync(
  outPath,
  `${banner}export const APP_VERSION: string = ${JSON.stringify(version)};\n`,
  "utf8",
);
console.log(`[gen-build-version] apps/shell version ${version} -> apps/host/src/build-version.ts`);
