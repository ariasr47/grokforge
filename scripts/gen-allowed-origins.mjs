#!/usr/bin/env node
/**
 * Generate apps/host/src/allowed-origins.ts from the channel's checked-in variant (SPEC §2.7 rule 4).
 * Usage: node scripts/gen-allowed-origins.mjs --channel=prod|dev
 * Channel selection happens HERE — at packaging / from-source-start time — and leaves no runtime
 * switch behind in the artifact.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const arg = process.argv.find((a) => a.startsWith("--channel="));
const raw = (arg?.split("=")[1] || process.env.GROKFORGE_CHANNEL || "prod").toLowerCase();
const channel = ["dev", "development", "tst", "test", "qa"].includes(raw) ? "dev" : "prod";

const srcDir = path.join(root, "apps", "host", "src");
const from = path.join(srcDir, `allowed-origins.${channel}.ts`);
const to = path.join(srcDir, "allowed-origins.ts");

if (!fs.existsSync(from)) {
  console.error(`[gen-allowed-origins] missing variant ${from}`);
  process.exit(1);
}

const banner =
  `// GENERATED by scripts/gen-allowed-origins.mjs — do not edit, do not commit (channel=${channel}).\n` +
  `// Source: allowed-origins.${channel}.ts. Gitignored on purpose: a skipped copy must FAIL the\n` +
  `// build with a missing module rather than silently ship the dev list (SPEC §2.7 rule 4).\n`;

fs.writeFileSync(to, banner + fs.readFileSync(from, "utf8"), "utf8");
console.log(`[gen-allowed-origins] channel=${channel} -> apps/host/src/allowed-origins.ts`);
